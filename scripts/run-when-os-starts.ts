// scripts/run-when-os-starts.ts
// 注册 / 注销 Windows 登录自启：当前项目根目录下运行 pnpm start
//
//   pnpm run-when-os-starts [install|uninstall|status]
//
// 实现（任务计划程序 ONLOGON，无 HKCU Run 兜底）：
// - Windows 上 detached 子进程仍属于父进程所在的 Job Object：从终端 / IDE / Agent
//   会话里启动的进程树，会在宿主关闭时被一并 TerminateProcess——表现为服务
//   「过一会就静默消失」，连退出码都来不及写进日志。
// - Task Scheduler 启动的进程挂在 taskhostw 下，与任何终端会话无关；登录即拉起。
// - 任务动作：wscript.exe "<root>\.vow\startup-launcher.vbs>"（无窗口 + 日志 + 重试）。
// - 执行时间限制 = 无限制（默认 72h 会掐断常驻服务）；多实例 = IgnoreNew。
// - install 会删除历史遗留的同名 Run 键，不做任何兜底。

import { spawnSync } from 'node:child_process'
import { writeFileSync, unlinkSync, existsSync, mkdirSync } from 'node:fs'
import { resolve, dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createConnection } from 'node:net'

const __dirname = dirname(fileURLToPath(import.meta.url))
const ROOT = resolve(__dirname, '..')
const DOT_VOW = resolve(ROOT, '.vow')
const LAUNCHER = join(DOT_VOW, 'startup-launcher.vbs')
const LOG = join(DOT_VOW, 'startup.log')

const TASK_NAME = 'vow-startup'
const REG_PATH = 'HKCU\\Software\\Microsoft\\Windows\\CurrentVersion\\Run'
const REG_VALUE = 'vow-startup'

/** 任务计划程序常见 LastTaskResult 的易读文案 */
const TASK_RESULT_LABEL: Record<string, string> = {
  '0': '成功',
  '267009': '正在运行',
  '267010': '任务已禁用',
  '267011': '尚未运行',
  '267012': '没有更多计划运行',
  '267014': '任务被用户终止',
}

const cmd = process.argv[2] ?? 'install'

// ── helpers ──

function ensureDotVow() {
  if (!existsSync(DOT_VOW)) mkdirSync(DOT_VOW, { recursive: true })
}

interface PsResult {
  status: number | null
  stdout: string
  stderr: string
}

/** 以环境变量传参，避免路径/引号在 -Command 字符串里的转义地狱 */
function powershell(script: string): PsResult {
  const r = spawnSync(
    'powershell.exe',
    ['-NoProfile', '-NonInteractive', '-ExecutionPolicy', 'Bypass', '-Command', script],
    {
      stdio: 'pipe',
      windowsHide: true,
      encoding: 'utf-8',
      env: {
        ...process.env,
        VOW_TASK_NAME: TASK_NAME,
        VOW_TASK_LAUNCHER: LAUNCHER,
        VOW_TASK_ROOT: ROOT,
      },
    },
  )
  if (r.error) throw r.error
  return { status: r.status, stdout: r.stdout ?? '', stderr: r.stderr ?? '' }
}

function psOrThrow(script: string, what: string): string {
  const r = powershell(script)
  if (r.status !== 0) {
    const detail = (r.stderr || r.stdout).trim()
    throw new Error(`${what}失败（exit ${r.status}）${detail ? `：${detail}` : ''}`)
  }
  return r.stdout.trim()
}

/** 写入无窗口启动 VBS：CWD 切到项目根后以隐藏窗口执行 pnpm start，并记录日志 */
function writeLauncher() {
  ensureDotVow()
  // 注意：VBS 字符串没有转义序列，Windows 路径必须保持单反斜杠
  // 注意：VBS 文件按 ANSI 解析（WSH 不认无 BOM 的 UTF-8），注释保持纯 ASCII
  const vbs = [
    "' vow startup launcher - generated by scripts/run-when-os-starts.ts, do not edit",
    "' Task Scheduler (ONLOGON) runs: wscript.exe \"<this file>\"; starts pnpm start hidden, log: .vow\\startup.log",
    'Dim sh, fso, logFile, attempt, rc, startedAt, failures',
    'Set sh = CreateObject("WScript.Shell")',
    'Set fso = CreateObject("Scripting.FileSystemObject")',
    `sh.CurrentDirectory = "${ROOT}"`,
    `logFile = "${LOG}"`,
    'Sub WriteLog(msg)',
    '  Dim f',
    '  Set f = fso.OpenTextFile(logFile, 8, True)',
    '  f.WriteLine "[" & Now & "] " & msg',
    '  f.Close',
    'End Sub',
    'WriteLog "=== logon launch: pnpm start ==="',
    'failures = 0',
    'Do',
    '  attempt = failures + 1',
    '  WriteLog "launch attempt " & attempt',
    '  startedAt = Now',
    '  rc = sh.Run("cmd /c pnpm start >> """ & logFile & """ 2>&1", 0, True)',
    '  WriteLog "pnpm exited with code " & rc',
    '  If rc = 0 Then',
    '    WriteLog "pnpm stopped normally - watchdog exits"',
    '    Exit Do',
    '  End If',
    "  ' ran longer than 60s counts as a healthy start: reset consecutive failures",
    '  If DateDiff("s", startedAt, Now) >= 60 Then failures = 0',
    '  failures = failures + 1',
    "  ' crash watchdog: retry 5s, back off to 60s after 4 consecutive quick failures",
    '  If failures >= 4 Then',
    '    WriteLog "too many consecutive failures - next retry in 60s"',
    '    WScript.Sleep 60000',
    '  Else',
    '    WriteLog "watchdog restart in 5s (consecutive failure " & failures & ")"',
    '    WScript.Sleep 5000',
    '  End If',
    'Loop',
    'WriteLog "=== launcher exit ==="',
  ].join('\r\n')
  writeFileSync(LAUNCHER, vbs, 'utf-8')
  console.log(`  ✓ 写入启动器: ${LAUNCHER}`)
}

function regDelete(): boolean {
  const r = spawnSync('reg', ['delete', REG_PATH, '/v', REG_VALUE, '/f'], {
    stdio: 'pipe',
    windowsHide: true,
  })
  return r.status === 0
}

function regQuery(): string | null {
  const r = spawnSync('reg', ['query', REG_PATH, '/v', REG_VALUE], {
    stdio: 'pipe',
    windowsHide: true,
    encoding: 'utf-8',
  })
  if (r.status !== 0) return null
  const m = (r.stdout ?? '').match(/REG_SZ\s+(.+)/)
  return m ? m[1].trim() : null
}

/** 检测 vow 后端是否已在运行（连 localhost:48085 TCP，超时 1.5s） */
function isAlreadyRunning(): Promise<boolean> {
  return new Promise((resolve) => {
    const sock = createConnection({ host: '127.0.0.1', port: 48085 }, () => {
      sock.destroy()
      resolve(true)
    })
    sock.on('error', () => resolve(false))
    sock.setTimeout(1500, () => {
      sock.destroy()
      resolve(false)
    })
  })
}

// ── PowerShell 片段 ──

/** 注册/更新 ONLOGON 任务：当前用户、交互式会话、无执行时限、失败重启守护 */
const PS_INSTALL = [
  "$ErrorActionPreference = 'Stop'",
  '$name = $env:VOW_TASK_NAME',
  '$old = Get-ScheduledTask -TaskName $name -ErrorAction SilentlyContinue',
  '$user = [System.Security.Principal.WindowsIdentity]::GetCurrent().Name',
  "$wscript = Join-Path $env:SystemRoot 'System32\\wscript.exe'",
  "$action = New-ScheduledTaskAction -Execute $wscript -Argument ('\"' + $env:VOW_TASK_LAUNCHER + '\"') -WorkingDirectory $env:VOW_TASK_ROOT",
  '$trigger = New-ScheduledTaskTrigger -AtLogOn -User $user',
  // 崩溃守护：VBS 重试耗尽后以非零码退出 → 任务计划程序按分钟级间隔重新拉起
  '$settings = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -ExecutionTimeLimit ([TimeSpan]::Zero) -MultipleInstances IgnoreNew -StartWhenAvailable -RestartCount 999 -RestartInterval (New-TimeSpan -Minutes 1)',
  "$desc = 'vow wireless mic: start pnpm start at logon (log: .vow/startup.log)'",
  // 已存在则热更新（Set 不会终止正在运行的实例；其参数集不含 Description，描述保持原值）
  "if ($old) { Set-ScheduledTask -TaskName $name -Action $action -Trigger $trigger -Settings $settings | Out-Null }",
  "else { Register-ScheduledTask -TaskName $name -Action $action -Trigger $trigger -Settings $settings -Description $desc -Force | Out-Null }",
  "'OK ' + $user",
].join('\n')

const PS_UNINSTALL = [
  "$ErrorActionPreference = 'Stop'",
  '$t = Get-ScheduledTask -TaskName $env:VOW_TASK_NAME -ErrorAction SilentlyContinue',
  'if ($t) { Unregister-ScheduledTask -TaskName $env:VOW_TASK_NAME -Confirm:$false; \'REMOVED\' } else { \'NOT_FOUND\' }',
].join('\n')

const PS_STATUS = [
  "$ErrorActionPreference = 'Stop'",
  '$t = Get-ScheduledTask -TaskName $env:VOW_TASK_NAME -ErrorAction SilentlyContinue',
  "if (-not $t) { 'NOT_REGISTERED'; exit 0 }",
  '$i = Get-ScheduledTaskInfo -TaskName $env:VOW_TASK_NAME',
  "'STATE=' + [string]$t.State",
  "$r = $i.LastRunTime; if ($r -and $r.Year -gt 2000) { 'LAST_RUN=' + $r.ToString('yyyy-MM-dd HH:mm:ss') } else { 'LAST_RUN=never' }",
  "'LAST_RESULT=' + $i.LastTaskResult",
  "'RESTART=' + $t.Settings.RestartCount + ' / ' + $t.Settings.RestartInterval",
  "'ACTION=' + $t.Actions[0].Execute + ' ' + $t.Actions[0].Arguments",
].join('\n')

const PS_START = [
  "$ErrorActionPreference = 'Stop'",
  'Start-ScheduledTask -TaskName $env:VOW_TASK_NAME',
].join('\n')

// ── commands ──

switch (cmd) {
  case 'install': {
    console.log('[vow] 注册 Windows 登录自启（任务计划程序）...')
    writeLauncher()

    // 无兜底：清理历史 Run 键（含旧版本写入的裸 .vbs 值）
    if (regDelete()) {
      console.log('  ✓ 已清理 HKCU Run 旧值（不再使用兜底）')
    } else {
      console.log('  · HKCU Run 无残留（干净）')
    }

    const user = psOrThrow(PS_INSTALL, '注册计划任务')
    console.log(`  ✓ 已注册计划任务 "${TASK_NAME}"（${user}，登录时启动，无执行时限）`)
    console.log(`  启动命令: wscript.exe "${LAUNCHER}"`)
    console.log(`  启动日志: ${LOG}`)
    console.log('  如需取消: pnpm run-when-os-starts uninstall')

    // 即刻启动——已有实例则跳过（旧实例可能仍挂在终端会话上，注销/重启后由任务接管）
    const running = await isAlreadyRunning()
    if (running) {
      console.log('  ⏭ 48085 已有实例在运行，跳过启动')
      console.log('    ⚠ 若它是终端会话启动的旧进程，关闭终端仍会被带走；注销/重启后由计划任务接管')
    } else {
      psOrThrow(PS_START, '启动计划任务')
      console.log('  ✓ 已通过任务计划程序启动')
    }
    process.exit(0)
  }

  case 'uninstall':
  case 'remove': {
    console.log('[vow] 移除 Windows 登录自启...')
    try {
      const r = psOrThrow(PS_UNINSTALL, '注销计划任务')
      console.log(r === 'REMOVED' ? `  ✓ 已注销计划任务 "${TASK_NAME}"` : `  · 计划任务 "${TASK_NAME}" 不存在`)
    } catch (err) {
      console.error(`  ✗ ${err instanceof Error ? err.message : err}`)
    }
    if (regDelete()) console.log('  ✓ 已清理历史 Run 键')
    try {
      if (existsSync(LAUNCHER)) unlinkSync(LAUNCHER)
      console.log(`  ✓ 已移除启动器: ${LAUNCHER}`)
    } catch {
      // 文件不存在也无妨
    }
    console.log('  · 当前运行中的服务不会被停止')
    break
  }

  case 'status': {
    const out = psOrThrow(PS_STATUS, '查询计划任务')
    if (out.startsWith('NOT_REGISTERED')) {
      console.log('[vow] 登录自启: 未注册计划任务')
    } else {
      console.log('[vow] 登录自启: 计划任务已注册 ✓')
      console.log(`  任务:   ${TASK_NAME}`)
      for (const line of out.split(/\r?\n/)) {
        const [k, ...rest] = line.split('=')
        const v = rest.join('=')
        if (k === 'STATE') console.log(`  状态:   ${v}`)
        if (k === 'LAST_RUN') console.log(`  上次运行: ${v}`)
        if (k === 'LAST_RESULT') {
          const label = TASK_RESULT_LABEL[v]
          console.log(`  上次结果: ${v}${label ? `（${label}）` : ''}`)
        }
        if (k === 'RESTART') {
          const [count, interval] = v.split(' / ')
          console.log(`  崩溃守护: 失败后每 ${interval} 重启（最多 ${count} 次）`)
        }
        if (k === 'ACTION') console.log(`  启动命令: ${v.trim()}`)
      }
      console.log(`  启动日志: ${existsSync(LOG) ? LOG : '（尚未产生）'}`)
    }
    const legacy = regQuery()
    if (legacy) {
      console.log(`  ⚠ 检测到遗留 Run 键（不再使用）: ${legacy}`)
      console.log('    运行 install 可清理')
    }
    break
  }

  default:
    console.error(`未知子命令: ${cmd}。可用: install | uninstall | status`)
    process.exit(1)
}
