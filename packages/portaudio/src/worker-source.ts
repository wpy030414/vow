// @vow/portaudio —— worker 源码字符串（eval / CJS 上下文执行）
//
// ⚠ 本字符串在 new Worker(code, { eval: true }) 的 CJS 环境中运行：
//   - 不得出现 TS 语法 / import / 模板字符串（反引号、${}）/ 对外层作用域的引用
//   - 只用 require + 普通字符串拼接；workerData = { dllPath, koffiPath }（均为绝对路径）
//   - 消息协议字段与 src/types.ts 必须同步维护（apps/server 的协议测试守护）
//   - FFI 声明经过真实探针验证（PortAudio V19.7.0-devel / koffi 3.3.3 / Node 26）
export const PORTAUDIO_WORKER_SOURCE = [
  "// vow portaudio worker (eval/CJS) —— 所有 Pa_* 调用只发生在本线程",
  "const { parentPort, workerData } = require('node:worker_threads')",
  "",
  "const koffi = require(workerData.koffiPath)",
  "const lib = koffi.load(workerData.dllPath)",
  "",
  "// ── C 类型（VOW_ 前缀，沿用 win32-keys 惯例）──",
  "// Windows LLP64：PaSampleFormat / PaStreamFlags / framesPerBuffer 的 unsigned long 均为 32 位 → uint32",
  "koffi.struct('VOW_PaDeviceInfo', {",
  "  structVersion: 'int',",
  "  name: 'const char *',",
  "  hostApi: 'int',",
  "  maxInputChannels: 'int',",
  "  maxOutputChannels: 'int',",
  "  defaultLowInputLatency: 'double',",
  "  defaultLowOutputLatency: 'double',",
  "  defaultHighInputLatency: 'double',",
  "  defaultHighOutputLatency: 'double',",
  "  defaultSampleRate: 'double'",
  "})",
  "koffi.struct('VOW_PaHostApiInfo', {",
  "  structVersion: 'int',",
  "  type: 'int',",
  "  name: 'const char *',",
  "  deviceCount: 'int',",
  "  defaultInputDevice: 'int',",
  "  defaultOutputDevice: 'int'",
  "})",
  "koffi.struct('VOW_PaStreamParameters', {",
  "  device: 'int',",
  "  channelCount: 'int',",
  "  sampleFormat: 'uint32',",
  "  suggestedLatency: 'double',",
  "  hostApiSpecificStreamInfo: 'void *'",
  "})",
  "koffi.opaque('VOW_PaStream')",
  "",
  "const Pa_Initialize = lib.func('int Pa_Initialize()')",
  "const Pa_Terminate = lib.func('int Pa_Terminate()')",
  "const Pa_GetDeviceCount = lib.func('int Pa_GetDeviceCount()')",
  "const Pa_GetDeviceInfo = lib.func('const VOW_PaDeviceInfo *Pa_GetDeviceInfo(int device)')",
  "const Pa_GetHostApiInfo = lib.func('const VOW_PaHostApiInfo *Pa_GetHostApiInfo(int hostApi)')",
  "const Pa_GetVersionText = lib.func('const char *Pa_GetVersionText()')",
  "const Pa_GetErrorText = lib.func('const char *Pa_GetErrorText(int code)')",
  "const Pa_OpenStream = lib.func('int Pa_OpenStream(_Out_ VOW_PaStream **stream, const VOW_PaStreamParameters *inParams, const VOW_PaStreamParameters *outParams, double sampleRate, uint32 framesPerBuffer, uint32 streamFlags, void *streamCallback, void *userData)')",
  "const Pa_StartStream = lib.func('int Pa_StartStream(VOW_PaStream *stream)')",
  "const Pa_WriteStream = lib.func('int Pa_WriteStream(VOW_PaStream *stream, const void *buffer, uint32 frames)')",
  "const Pa_StopStream = lib.func('int Pa_StopStream(VOW_PaStream *stream)')",
  "const Pa_CloseStream = lib.func('int Pa_CloseStream(VOW_PaStream *stream)')",
  "",
  "const PA_NO_ERROR = 0",
  "const PA_FLOAT32 = 0x1",
  "const PA_NO_FLAG = 0",
  "const FRAMES_PER_BUFFER = 1024",
  "",
  "let initCount = 0",
  "let tokenSeq = 0",
  "const streams = new Map()",
  "",
  "function errText(code) {",
  "  try { return Pa_GetErrorText(code) } catch (e) { return 'PaError ' + code }",
  "}",
  "function ensureInit() {",
  "  if (initCount === 0) {",
  "    const e = Pa_Initialize()",
  "    if (e !== PA_NO_ERROR) throw new Error('Pa_Initialize failed: ' + errText(e))",
  "  }",
  "  initCount++",
  "}",
  "function releaseInit() {",
  "  if (initCount > 0) {",
  "    initCount--",
  "    if (initCount === 0) { try { Pa_Terminate() } catch (e) { /* noop */ } }",
  "  }",
  "}",
  "function readDevices() {",
  "  const count = Pa_GetDeviceCount()",
  "  if (count < 0) throw new Error('Pa_GetDeviceCount failed: ' + errText(count))",
  "  const list = []",
  "  for (let i = 0; i < count; i++) {",
  "    // const Struct * 返回 BigInt 指针，必须显式 decode（探针踩坑）",
  "    const d = koffi.decode(Pa_GetDeviceInfo(i), 'VOW_PaDeviceInfo')",
  "    const api = koffi.decode(Pa_GetHostApiInfo(d.hostApi), 'VOW_PaHostApiInfo')",
  "    list.push({",
  "      id: i, name: d.name, hostAPIName: api.name,",
  "      maxInputChannels: d.maxInputChannels,",
  "      maxOutputChannels: d.maxOutputChannels,",
  "      defaultSampleRate: d.defaultSampleRate,",
  "      defaultLowOutputLatency: d.defaultLowOutputLatency",
  "    })",
  "  }",
  "  return list",
  "}",
  "function closeStreamEntry(token) {",
  "  const s = streams.get(token)",
  "  if (!s) return",
  "  streams.delete(token)",
  "  try { Pa_StopStream(s.handle) } catch (e) { /* noop */ }",
  "  try { Pa_CloseStream(s.handle) } catch (e) { /* noop */ }",
  "  releaseInit()",
  "}",
  "function safeVersion() { try { return Pa_GetVersionText() } catch (e) { return 'unknown' } }",
  "",
  "function handle(msg) {",
  "  if (msg.op === 'getDevices') {",
  "    // 无流时走一次性 Initialize→枚举→Terminate（复刻 naudiodon：重扫必新鲜枚举）",
  "    if (initCount === 0) {",
  "      ensureInit()",
  "      try { return readDevices() } finally { releaseInit() }",
  "    }",
  "    return readDevices()",
  "  }",
  "  if (msg.op === 'openOutput') {",
  "    ensureInit()",
  "    try {",
  "      const info = koffi.decode(Pa_GetDeviceInfo(msg.deviceId), 'VOW_PaDeviceInfo')",
  "      const params = {",
  "        device: msg.deviceId,",
  "        channelCount: msg.channelCount,",
  "        sampleFormat: PA_FLOAT32,",
  "        suggestedLatency: info.defaultLowOutputLatency,",
  "        hostApiSpecificStreamInfo: null",
  "      }",
  "      const out = [null]",
  "      let e = Pa_OpenStream(out, null, params, msg.sampleRate, FRAMES_PER_BUFFER, PA_NO_FLAG, null, null)",
  "      if (e !== PA_NO_ERROR) throw new Error('Pa_OpenStream failed: ' + errText(e))",
  "      e = Pa_StartStream(out[0])",
  "      if (e !== PA_NO_ERROR) { try { Pa_CloseStream(out[0]) } catch (e2) { /* noop */ } throw new Error('Pa_StartStream failed: ' + errText(e)) }",
  "      const token = ++tokenSeq",
  "      streams.set(token, { handle: out[0], frames: FRAMES_PER_BUFFER, channels: msg.channelCount })",
  "      return { token: token }",
  "    } catch (err) { releaseInit(); throw err }",
  "  }",
  "  if (msg.op === 'closeOutput') { closeStreamEntry(msg.token); return {} }",
  "  if (msg.op === 'shutdown') {",
  "    for (const token of Array.from(streams.keys())) closeStreamEntry(token)",
  "    while (initCount > 0) releaseInit()",
  "    return { version: safeVersion() }",
  "  }",
  "  throw new Error('unknown op: ' + String(msg.op))",
  "}",
  "",
  "parentPort.on('message', function (msg) {",
  "  if (msg.kind === 'write') {",
  "    const s = streams.get(msg.token)",
  "    if (!s) return",
  "    if (!msg.audio || msg.audio.length !== s.frames * s.channels) return",
  "    const e = Pa_WriteStream(s.handle, msg.audio, s.frames)",
  "    if (e !== PA_NO_ERROR) {",
  "      // 复刻 naudiodon closeOnError: true —— 上报并就地销毁流",
  "      parentPort.postMessage({ kind: 'streamError', token: msg.token, code: e, message: errText(e) })",
  "      closeStreamEntry(msg.token)",
  "    }",
  "    return",
  "  }",
  "  if (msg.kind === 'req') {",
  "    try {",
  "      const result = handle(msg)",
  "      parentPort.postMessage({ kind: 'reply', id: msg.id, ok: true, result: result })",
  "    } catch (err) {",
  "      parentPort.postMessage({ kind: 'reply', id: msg.id, ok: false, error: (err && err.message) ? err.message : String(err) })",
  "    }",
  "  }",
  "})",
].join('\n')
